import random
import time
import statistics
import matplotlib.pyplot as plt

random.seed(12345)

def programacion_dinamica(monedas):
    n = len(monedas)

    if n == 0:
        return 0

    dp = [[0] * n for _ in range(n)]

    for i in range(n):
        dp[i][i] = monedas[i]

    for longitud in range(2, n + 1):
        for i in range(n - longitud + 1):
            j = i + longitud - 1

            mateo_izq = monedas[i + 1]
            mateo_der = monedas[j]

            if mateo_izq >= mateo_der:
                izquierda = monedas[i] + (dp[i + 2][j] if i + 2 <= j else 0)
            else:
                izquierda = monedas[i] + (dp[i + 1][j - 1] if i + 1 <= j - 1 else 0)

            mateo_izq = monedas[i]
            mateo_der = monedas[j - 1]

            if mateo_izq >= mateo_der:
                derecha = monedas[j] + (dp[i + 1][j - 1] if i + 1 <= j - 1 else 0)
            else:
                derecha = monedas[j] + (dp[i][j - 2] if i <= j - 2 else 0)

            dp[i][j] = max(izquierda, derecha)

    return dp[0][n - 1]


tamanios = [100, 200, 400, 600, 800, 1000]
repeticiones = 15

tiempos = []

for n in tamanios:
    monedas = [random.randint(1, 1000) for _ in range(n)]

    programacion_dinamica(monedas)

    mediciones = []

    for _ in range(repeticiones):
        inicio = time.perf_counter()
        programacion_dinamica(monedas)
        fin = time.perf_counter()

        mediciones.append(fin - inicio)

    tiempo_mediano = statistics.median(mediciones)
    tiempos.append(tiempo_mediano)

    print(f"n = {n}: "
        f"{tiempo_mediano:.6f} segundos")


plt.figure(figsize=(8, 5))
plt.plot(tamanios, tiempos, marker="o")
plt.title("Tiempo de ejecución según el tamaño de entrada")
plt.xlabel("Cantidad de monedas (n)")
plt.ylabel("Tiempo mediano (segundos)")
plt.grid(True)
plt.tight_layout()
plt.show()